<?php

namespace App\Http\Requests;

use App\Models\User;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;
use Illuminate\Validation\Rules\Password;

class UpdateCoordinatorRequest extends FormRequest
{
    public function authorize(): bool
    {
        return $this->user()?->role === 'admin' && $this->user()?->status === 'active';
    }

    public function rules(): array
    {
        /** @var User $coordinator */
        $coordinator = $this->route('coordinator');

        return [
            'name' => ['required', 'string', 'max:255'],
            'email' => ['required', 'email', 'max:255', Rule::unique('users', 'email')->ignore($coordinator)],
            'password' => ['nullable', 'confirmed', Password::min(8)],
            'status' => ['required', 'in:active,inactive,suspended'],
        ];
    }
}
